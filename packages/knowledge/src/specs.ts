import { readdir, realpath } from "node:fs/promises";
import { isAbsolute, join, relative } from "node:path";
import { coverageOf, SPEC_ICON, type SpecCoverage, type SpecDraft, type SpecEvidence, type VerifiedClaim, type VerifiedSpec } from "@navarch/contracts";
import { readText } from "@navarch/explorer";

/** A quote counts when it appears on the cited line or within this many lines of it. */
const QUOTE_WINDOW = 2;
const MIN_QUOTE = 8;

const squash = (s: string) => s.replace(/\s+/g, " ").trim();

type Checked = SpecEvidence & { valid: boolean; quoted: boolean };

/** One piece of evidence against the files of `root`: it must exist, the line must exist, and a quote must be there. */
async function checkEvidence(root: string, ev: SpecEvidence, cache: Map<string, string[] | null>): Promise<Checked> {
  const bad = { ...ev, valid: false, quoted: false };
  if (isAbsolute(ev.file) || ev.file.split(/[\\/]/).includes("..")) return bad;
  let lines = cache.get(ev.file);
  if (lines === undefined) {
    lines = null;
    let inside = false;
    try {
      // A symlink that leaves the repository is not evidence from it.
      const rel = relative(await realpath(root), await realpath(join(root, ev.file)));
      inside = rel !== "" && !rel.startsWith("..") && !isAbsolute(rel);
    } catch {
      // Missing file: the evidence is invalid.
    }
    if (inside) {
      const text = await readText(root, ev.file);
      if (text !== undefined) lines = text.split("\n");
    }
    cache.set(ev.file, lines);
  }
  if (!lines || ev.line > lines.length) return bad;
  const quote = ev.quote ? squash(ev.quote) : "";
  if (!quote) return { ...ev, valid: true, quoted: false };
  const window = squash(lines.slice(Math.max(0, ev.line - 1 - QUOTE_WINDOW), ev.line + QUOTE_WINDOW).join("\n"));
  return window.includes(quote) ? { ...ev, valid: true, quoted: quote.length >= MIN_QUOTE } : bad;
}

/**
 * Checks every claim of the drafts against the code in `root` (ADR 0045). A claim the agent calls
 * 🟢 keeps it only when every piece of evidence has its file and line really there and one of them carries the quote; otherwise
 * it becomes 🟡 and says why. 🟡 and 🔴 claims are kept, with their evidence marked valid or not.
 */
export async function verifyDrafts(root: string, drafts: readonly SpecDraft[]): Promise<VerifiedSpec[]> {
  const cache = new Map<string, string[] | null>();
  const out: VerifiedSpec[] = [];
  for (const draft of drafts) {
    const claims: VerifiedClaim[] = [];
    for (const claim of draft.claims) {
      const checked: Checked[] = [];
      for (const ev of claim.evidence) checked.push(await checkEvidence(root, ev, cache));
      let confidence = claim.confidence;
      let reason: string | undefined;
      if (confidence === "confirmed" && !(checked.some((c) => c.valid && c.quoted) && checked.every((c) => c.valid))) {
        confidence = "inferred";
        reason = !claim.evidence.length
          ? "no evidence given"
          : checked.some((c) => c.valid && c.quoted)
            ? "a cited file, line or quote was not found in the code"
            : checked.some((c) => c.valid)
            ? `no quote of at least ${MIN_QUOTE} characters found at the cited line`
            : "the cited file, line or quote was not found in the code";
      }
      claims.push({
        id: claim.id,
        text: claim.text,
        stated: claim.confidence,
        confidence,
        ...(reason ? { reason } : {}),
        evidence: checked.map(({ quoted: _quoted, ...ev }) => ev),
      });
    }
    out.push({ component: draft.component, title: draft.title, summary: draft.summary, claims });
  }
  return out;
}

const cell = (s: string) => s.replace(/\r?\n/g, " ").replace(/\s+/g, " ").trim();

/** The component's Markdown file. Text comes from an agent reading untrusted code; it is shown, never run. */
export function renderSpec(spec: VerifiedSpec, meta: { runId: string; generatedAt: string }): string {
  const cov = coverageOf([spec]);
  const lines = [
    `# ${cell(spec.title)}`,
    "",
    `Component \`${spec.component}\` · generated by Navarch run \`${meta.runId}\` on ${meta.generatedAt.slice(0, 10)} · ${cov.confirmed}/${cov.claims} claims confirmed`,
    "",
    "🟢 confirmed from the code (file, line and quote checked by Navarch) · 🟡 inferred · 🔴 gap, needs a human",
    "",
    cell(spec.summary),
    "",
    "## Claims",
    "",
  ];
  for (const c of spec.claims) {
    const where = c.evidence.map((e) => `\`${e.file}:${e.line}\`${e.valid ? "" : " (not found)"}`).join(", ");
    lines.push(`- ${SPEC_ICON[c.confidence]} **${c.id}** ${cell(c.text)}${where ? ` — ${where}` : ""}${c.reason ? ` _(stated confirmed; lowered: ${c.reason})_` : ""}`);
  }
  return `${lines.join("\n")}\n`;
}

export function renderIndex(specs: readonly VerifiedSpec[], meta: { runId: string; generatedAt: string }): { markdown: string; json: string; coverage: SpecCoverage } {
  const coverage = coverageOf(specs);
  const pct = (n: number | null) => (n === null ? "-" : `${Math.round(n * 100)} %`);
  const rows = specs.map((s) => {
    const c = coverageOf([s]);
    return `| [${cell(s.title)}](${s.component}.md) | ${c.claims} | ${c.confirmed} | ${c.inferred} | ${c.gap} | ${pct(c.green_rate)} |`;
  });
  const markdown = [
    "# Specifications",
    "",
    `Generated by Navarch run \`${meta.runId}\` on ${meta.generatedAt.slice(0, 10)}. ${coverage.confirmed} of ${coverage.claims} claims are 🟢 (${pct(coverage.green_rate)}); ${coverage.downgraded} stated as confirmed were lowered because their evidence did not check out.`,
    "",
    "| Component | Claims | 🟢 | 🟡 | 🔴 | 🟢 share |",
    "|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
  const json = `${JSON.stringify({ run_id: meta.runId, generated_at: meta.generatedAt, coverage, components: specs.map((s) => ({ component: s.component, file: `${s.component}.md`, ...coverageOf([s]) })) }, null, 2)}\n`;
  return { markdown, json, coverage };
}

const SPECS_DIR = ".navarch/specs";
const MAX_SPEC_HITS = 50;

/**
 * Lines of the specification files under `.navarch/specs/` that contain every word of the query
 * (case-insensitive). The files are text an agent wrote from untrusted code: shown, never run.
 */
export async function searchSpecs(root: string, query: string): Promise<{ file: string; line: number; text: string }[]> {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  let names: string[];
  try {
    // Regular files only: a symlink in an untrusted repository must not lead outside it.
    names = (await readdir(join(root, SPECS_DIR), { withFileTypes: true })).filter((e) => e.isFile() && e.name.endsWith(".md")).map((e) => e.name).sort();
  } catch {
    return [];
  }
  const hits: { file: string; line: number; text: string }[] = [];
  for (const name of names) {
    const file = `${SPECS_DIR}/${name}`;
    const text = await readText(root, file);
    if (text === undefined) continue;
    const lines = text.split(/\r?\n/);
    for (let i = 0; i < lines.length && hits.length < MAX_SPEC_HITS; i++) {
      const lower = lines[i]!.toLowerCase();
      if (words.every((w) => lower.includes(w))) hits.push({ file, line: i + 1, text: lines[i]!.trim().slice(0, 400) });
    }
  }
  return hits;
}
